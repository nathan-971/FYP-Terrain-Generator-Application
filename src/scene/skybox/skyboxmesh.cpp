void SkyboxMesh::UpdateBuffers()
{
    glBindVertexArray(VAO);

    uploadVertexData(vertices.data(), vertices.size(), GL_STATIC_DRAW);
    enableAttribPointer(0, 3, GL_FLOAT, GL_FALSE, sizeof(Vertex), offsetof(Vertex, position));
}